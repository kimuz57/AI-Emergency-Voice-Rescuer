  // Deterministic "someone shouting for help" envelope: a few syllable bursts.
  function peaks(n, seed) {
    let x = seed || 7;
    const rand = () => ((x = (x * 1103515245 + 12345) % 2147483648) / 2147483648);
    const bursts = [[0.12, 0.05], [0.22, 0.06], [0.33, 0.045], [0.5, 0.07], [0.61, 0.05], [0.74, 0.06], [0.86, 0.04]];
    const out = [];
    for (let i = 0; i < n; i++) {
      const t = i / n;
      let e = 0.04;
      bursts.forEach(([c, w], k) => { e += (0.55 + 0.45 * ((k * 37) % 10) / 10) * Math.exp(-((t - c) ** 2) / (2 * w * w)); });
      out.push(Math.min(1, e) * (0.55 + 0.45 * rand()));
    }
    const max = Math.max.apply(null, out);
    return out.map((v) => v / max); // normalize: true
  }

